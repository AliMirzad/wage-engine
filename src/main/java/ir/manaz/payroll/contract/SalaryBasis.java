package ir.manaz.payroll.contract;

/**
 * مبنای محاسبه حقوق پایه.
 * <p>
 * خصوصیت قرارداد است نه شخص — یک کارگر می‌تواند روی یک پروژه ماهانه
 * و روی پروژه دیگر روزمزد باشد.
 */
public enum SalaryBasis {
    /** حقوق ماهانه ثابت */
    MONTHLY,
    /** دستمزد روزانه — در عدد روزهای کارکرد ضرب می‌شود */
    DAILY,
    /** دستمزد ساعتی */
    HOURLY
}